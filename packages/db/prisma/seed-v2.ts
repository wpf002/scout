/**
 * Synthetic resolution fixtures.
 *
 * About five hundred observations describing about a hundred and twenty
 * made-up entities, from three made-up sources, with every observation
 * carrying the entity it truly belongs to. No real person, vessel or aircraft
 * appears here: names are drawn from short lists, phones use the 555 exchange,
 * MMSIs and tail numbers are generated.
 *
 * Deterministic. The same seed produces the same rows and the same content
 * hashes, so the evaluation harness in services/resolution/eval can key its
 * expectations on hash rather than on ids the database assigns.
 *
 * The ground truth rides in `rawPayload._synthetic`. Normalizers and the
 * resolver never read `_synthetic`; the harness strips it before scoring.
 * Reading it would be cheating, and a test that lets the model cheat proves
 * nothing.
 */
