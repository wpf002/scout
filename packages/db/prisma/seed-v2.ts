// ── noise ─────────────────────────────────────────────────────────────────

function nameVariant(p: Person): { first: string; last: string } {
  const r = rand();
  if (r < 0.25 && NICK[p.first] !== undefined) return { first: NICK[p.first] as string, last: p.last };
  if (r < 0.4) return { first: `${p.first[0]}.`, last: p.last };
  if (r < 0.55) return { first: p.first.toUpperCase(), last: p.last.toUpperCase() };
  if (r < 0.65 && p.last.length > 4) return { first: p.first, last: p.last.slice(0, 3) + p.last.slice(4) };
  return { first: p.first, last: p.last };
}
function emailVariant(email: string): string {
  const [local, host] = email.split("@") as [string, string];
  const r = rand();
  if (r < 0.3) return `${local.replace(/\./g, "")}@${host}`;
  if (r < 0.5) return `${local}+news@${host}`;
  if (r < 0.7) return email.toUpperCase();
  return email;
}
function phoneVariant(e164: string): string {
  const d = e164.slice(2);
  const r = rand();
  if (r < 0.3) return `(${d.slice(0, 3)}) ${d.slice(3, 6)}-${d.slice(6)}`;
  if (r < 0.5) return `${d.slice(0, 3)}.${d.slice(3, 6)}.${d.slice(6)}`;
  if (r < 0.7) return `+1 ${d.slice(0, 3)} ${d.slice(3, 6)} ${d.slice(6)}`;
  return e164;
}
function addressVariant(a: string): string {
  const r = rand();
  if (r < 0.4) return a.replace(" Street,", " St,");
  if (r < 0.6) return `${a.split(",")[0] as string} Apt ${int(1, 30)},${a.split(",")[1] as string}`;
  return a;
}
const jitter = (v: number, by: number): number => v + (rand() - 0.5) * by;

// ── observations ──────────────────────────────────────────────────────────

const naive = (v: string): string => v.trim().toLowerCase();
const phoneDigits = (v: string): string => v.replace(/\D/g, "").replace(/^1(\d{10})$/, "$1");

interface Extracted { kind: string; value: string; normalizedValue: string }
interface Built { row: ObservationRow; identifiers: Extracted[]; truthKey: string; kind: Truth["kind"]; note?: string }

function canonicalJson(value: unknown): string {
  const sort = (v: unknown): unknown =>
    Array.isArray(v) ? v.map(sort)
    : v !== null && typeof v === "object"
      ? Object.fromEntries(Object.keys(v as Record<string, unknown>).sort().map((k) => [k, sort((v as Record<string, unknown>)[k])]))
      : v;
  return JSON.stringify(sort(value));
}
const hashOf = (normalized: Record<string, unknown>): string =>
  createHash("sha256").update(canonicalJson(normalized), "utf8").digest("hex");

const T0 = Date.UTC(2026, 5, 1);
const observedAt = (): Date => new Date(T0 + int(0, 90) * 86_400_000 + int(0, 86_399) * 1000);

function build(sourceId: string, truth: Truth, normalized: Record<string, unknown>, identifiers: Extracted[], position: { lon: number; lat: number } | null, note?: string): Built {
  const observed = observedAt();
  const raw = { ...normalized, _synthetic: { truthKey: truth.key, kind: truth.kind, ...(note === undefined ? {} : { note }) } };
  const row: ObservationRow = {
    sourceId,
    authorizationId: AUTHORIZATION_ID,
    collectedAt: new Date(observed.getTime() + int(1, 3600) * 1000),
    observedAt: observed,
    rawPayload: raw,
    normalizedPayload: normalized,
    contentHash: hashOf(normalized),
    position,
    confidenceBp: chance(0.8) ? int(6000, 10_000) : null,
    indeterminate: false,
    entityKind: truth.kind,
  };
  return { row, identifiers, truthKey: truth.key, kind: truth.kind, ...(note === undefined ? {} : { note }) };
}

const built: Built[] = [];

for (const t of truths) {
  if (t.kind === "PERSON") {
    const n = int(3, 6);
    for (let i = 0; i < n; i += 1) {
      const src = pick(["synth-records", "synth-broker", "synth-broker", "synth-sensor"] as const);
      const name = nameVariant(t);
      const pos = src === "synth-sensor" || chance(0.3) ? { lon: jitter(t.city.lon, 0.04), lat: jitter(t.city.lat, 0.04) } : null;
      if (src === "synth-records") {
        const address = addressVariant(t.address);
        const normalized = { name: `${name.first} ${name.last}`, address, city: t.city.name, documentNo: chance(0.5) ? `DOC-${digits(7)}` : undefined };
        built.push(build(src, t, normalized, [
          { kind: "NAME", value: normalized.name, normalizedValue: naive(normalized.name) },
          { kind: "ADDRESS", value: address, normalizedValue: naive(address) },
        ], pos));
      } else if (src === "synth-broker") {
        const email = emailVariant(t.email); const phone = phoneVariant(t.phone);
        const normalized = { name: `${name.first} ${name.last}`, email, phone, handle: chance(0.6) ? t.handle : undefined };
        built.push(build(src, t, normalized, [
          { kind: "NAME", value: normalized.name, normalizedValue: naive(normalized.name) },
          { kind: "EMAIL", value: email, normalizedValue: naive(email) },
          { kind: "PHONE", value: phone, normalizedValue: phoneDigits(phone) },
          ...(normalized.handle === undefined ? [] : [{ kind: "HANDLE", value: normalized.handle, normalizedValue: naive(normalized.handle) }]),
        ], pos));
      } else {
        const phone = phoneVariant(t.phone);
        const normalized = { deviceId: `dev-${createHash("sha1").update(t.key).digest("hex").slice(0, 10)}`, phone, seenNear: t.city.name };
        built.push(build(src, t, normalized, [
          { kind: "DEVICE_ID", value: normalized.deviceId, normalizedValue: normalized.deviceId },
          { kind: "PHONE", value: phone, normalizedValue: phoneDigits(phone) },
        ], pos));
      }
    }
  } else if (t.kind === "VESSEL") {
    const n = int(3, 5);
    for (let i = 0; i < n; i += 1) {
      const src = pick(["synth-sensor", "synth-sensor", "synth-records"] as const);
      const mmsi = t.key === "vessel-007" && i === 0 ? `${t.mmsi.slice(0, 8)}${(Number(t.mmsi[8]) + 1) % 10}` : t.mmsi;
      const note = mmsi === t.mmsi ? undefined : "hard: mmsi off by one digit; expect REVIEW or INDETERMINATE";
      const normalized = src === "synth-sensor"
        ? { mmsi, name: chance(0.7) ? t.name : t.name.toUpperCase(), sog: int(0, 20), cog: int(0, 359) }
        : { name: t.name, imo: t.imo, callsign: t.callsign, flag: pick(["NO", "CA", "IE", "CL"]) };
      const ids: Extracted[] = [{ kind: "NAME", value: t.name, normalizedValue: naive(t.name) }];
      if ("mmsi" in normalized) ids.push({ kind: "MMSI", value: mmsi, normalizedValue: mmsi });
      if ("imo" in normalized) ids.push({ kind: "IMO", value: t.imo, normalizedValue: t.imo });
      built.push(build(src, t, normalized, ids, src === "synth-sensor" ? { lon: jitter(t.lon, 0.5), lat: jitter(t.lat, 0.5) } : null, note));
    }
  } else if (t.kind === "ORG") {
    const n = int(3, 5);
    const LONG: Record<string, string> = { Inc: "Incorporated", LLC: "L.L.C.", Ltd: "Limited", Corp: "Corporation" };
    for (let i = 0; i < n; i += 1) {
      const src = pick(["synth-records", "synth-records", "synth-broker"] as const);
      const r = rand();
      const name =
        r < 0.3 ? `${t.name} ${t.suffix}`
        : r < 0.5 ? `${t.name.toUpperCase()}, ${t.suffix.toUpperCase()}.`
        : r < 0.7 ? `${t.name} ${LONG[t.suffix] as string}`
        : r < 0.85 ? t.name
        : `${t.name} ${t.suffix}.`;
      const normalized = src === "synth-records"
        ? { title: name, cik: chance(0.8) ? t.cik : undefined, ticker: t.ticker ?? undefined, jurisdiction: "US", city: t.city.name }
        : { name, ticker: t.ticker ?? undefined, city: t.city.name, domain: `${t.name.split(" ")[0]?.toLowerCase() as string}.example` };
      const ids: Extracted[] = [{ kind: "NAME", value: name, normalizedValue: naive(name) }];
      if ("cik" in normalized && normalized.cik !== undefined) ids.push({ kind: "DOCUMENT_NO", value: `CIK${t.cik}`, normalizedValue: `CIK${t.cik}` });
      if ("domain" in normalized) ids.push({ kind: "DOMAIN", value: normalized.domain, normalizedValue: normalized.domain });
      built.push(build(src, t, normalized, ids, null));
    }
  } else {
    const n = int(3, 4);
    for (let i = 0; i < n; i += 1) {
      const src = pick(["synth-sensor", "synth-records"] as const);
      const normalized = src === "synth-sensor"
        ? { icaoHex: t.icaoHex, callsign: chance(0.5) ? t.tail : undefined, altitudeFt: int(1000, 41_000) }
        : { tail: t.tail, type: t.type, icaoHex: chance(0.5) ? t.icaoHex.toUpperCase() : undefined };
      const ids: Extracted[] = [];
      if (normalized.icaoHex !== undefined) ids.push({ kind: "ICAO_HEX", value: normalized.icaoHex, normalizedValue: naive(normalized.icaoHex) });
      if ("tail" in normalized) ids.push({ kind: "TAIL_NUMBER", value: t.tail, normalizedValue: t.tail.toUpperCase() });
      built.push(build(src, t, normalized, ids, src === "synth-sensor" ? { lon: jitter(t.lon, 1), lat: jitter(t.lat, 1) } : null));
    }
  }
}

// ── write ─────────────────────────────────────────────────────────────────

async function main(): Promise<void> {
  const now = new Date();
  await prisma.authorization.upsert({
    where: { id: AUTHORIZATION_ID },
    update: {},
    create: {
      id: AUTHORIZATION_ID,
      reference: "SYNTHETIC-DEV-0001",
      issuedBy: "Scout fixture generator (synthetic data; no real persons or platforms)",
      boundary: { scope: [], entityKinds: [] },
      sourceClasses: ["PUBLIC_RECORD", "SENSOR", "BROKER"],
      // BIOMETRIC_COMPARE too: the synthetic case is the sandbox for the
      // recognition screen, against a gallery of made-up people.
      actionClasses: ["COLLECT", "RESOLVE", "READ_GRAPH", "BIOMETRIC_COMPARE"],
      validFrom: new Date(now.getTime() - 86_400_000),
      validUntil: new Date(now.getTime() + 10 * 365 * 86_400_000),
      createdBy: "seed-v2",
    },
  });

  // A case for the fixtures, so the console and the v2 routes can reach them.
  // Named so nobody mistakes it for an engagement.
  const existingCase = await prisma.case.findFirst({ where: { authorizationRef: "SYNTHETIC-DEV-0001" } });
  const fixtureCase =
    existingCase !== null
      ? await prisma.case.update({ where: { id: existingCase.id }, data: { authorizationId: AUTHORIZATION_ID } })
      : await prisma.case.create({
          data: {
            name: "Synthetic Fixtures",
            authorizationRef: "SYNTHETIC-DEV-0001",
            authorizationId: AUTHORIZATION_ID,
            notes: "Generated by packages/db/prisma/seed-v2.ts. Every person, vessel, aircraft and company here is made up.",
            createdBy: "seed-v2",
          },
        });
  for (const b of built) b.row.caseId = fixtureCase.id;

  for (const s of SOURCES) {
    await prisma.collectionSource.upsert({
      where: { id: s.id },
      update: {},
      create: { id: s.id, name: s.name, class: s.class, licensingTerms: s.licensingTerms, refreshCadenceSeconds: s.refreshCadenceSeconds },
    });
  }

  // Deterministic ids, so a re-run is a no-op rather than a duplicate set.
  for (const b of built) b.row.id = `obs_${b.row.contentHash.slice(0, 24)}`;
  const written = new Set(await insertObservations(built.map((b) => b.row)));

  const identifierRows = built
    .filter((b) => written.has(b.row.id as string))
    .flatMap((b) => b.identifiers.map((i) => ({
      observationId: b.row.id as string,
      kind: i.kind as never,
      value: i.value,
      normalizedValue: i.normalizedValue,
      normalizationVersion: NORMALIZATION_VERSION,
    })));
  if (identifierRows.length > 0) await prisma.identifier.createMany({ data: identifierRows });

  // The harness's copy. Keyed on contentHash, never on database ids.
  const here = dirname(fileURLToPath(import.meta.url));
  const out = resolve(here, "../../../services/resolution/eval/fixtures");
  mkdirSync(out, { recursive: true });
  const byKey = new Map<string, number>();
  for (const b of built) byKey.set(b.truthKey, (byKey.get(b.truthKey) ?? 0) + 1);
  writeFileSync(
    resolve(out, "synthetic.json"),
    JSON.stringify(
      {
        generatedBy: "packages/db/prisma/seed-v2.ts",
        seed: SEED,
        normalizationVersion: NORMALIZATION_VERSION,
        entities: truths.map((t) => ({ truthKey: t.key, kind: t.kind, observations: byKey.get(t.key) ?? 0 })),
        // Payload and identifiers ride along so the harness needs no database:
        // it resolves from this file alone and scores against truthKey.
        observations: built.map((b) => ({
          id: b.row.id,
          contentHash: b.row.contentHash,
          sourceId: b.row.sourceId,
          truthKey: b.truthKey,
          kind: b.kind,
          observedAt: b.row.observedAt.toISOString(),
          position: b.row.position,
          payload: b.row.normalizedPayload,
          identifiers: b.identifiers.map((i) => ({ kind: i.kind, value: i.value })),
          ...(b.note === undefined ? {} : { note: b.note }),
        })),
        hardCases: {
          sharedFullName: truths.filter((t) => t.kind === "PERSON" && Number(t.key.slice(-3)) >= 85).map((t) => t.key),
          mmsiOffByOne: ["vessel-007"],
        },
      },
      null,
      2,
    ),
  );

  console.log(`seed-v2: ${truths.length} entities, ${built.length} observations built, ${written.size} written, ${identifierRows.length} identifiers`);
}

main()
  .catch((error: unknown) => {
    console.error("seed-v2 failed:", error);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
